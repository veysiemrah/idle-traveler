const assert=require('node:assert/strict');
require('../public/js/data.js');for(const m of ['content','expeditions','migration','progression'])require('../public/js/v2/'+m+'.js');
const V=IT.V2;
let s=V.createState();s.unlockedWorlds=V.WORLDS.map(w=>w.id);s.worldId='galaxies';
s=V.startFleet(s,0,'galaxies-chart','guide',1).state;
assert.equal(s.fleet.length,1);assert.equal(s.expedition,null);assert.equal(s.worldId,'galaxies');
assert.throws(()=>V.startFleet(s,0,'galaxies-fleet','researcher',2));
assert.throws(()=>V.startFleet(s,1,'galaxies-fleet','guide',2));
s=V.startFleet(s,1,'galaxies-fleet','engineer',2).state;
s=V.advanceAll(s,10000,{capSeconds:10000}).state;
assert.equal(s.fleet[0].status,'awaitingChoice');assert.equal(s.fleet[1].status,'awaitingChoice');
const second=JSON.stringify(s.fleet[1]);
s=V.fleetAction(s,0,'choose',V.TEMPLATE[s.fleet[0].templateId].nodes[0].choices[0].id).state;
assert.equal(JSON.stringify(s.fleet[1]),second);
assert.equal(s.fleet[0].nodeIndex,1);
assert.equal(s.fleet[0].loadout.role,'guide');
let c=V.createState();
assert.throws(()=>V.startFleet(c,0,'earth-survey','guide',1));
assert.ok(V.COSTS.reduce((a,b)=>a+b,0)*3<=V.TEMPLATES.reduce((a,t)=>a+t.research,0));
let bad=V.clone(s);bad.fleet.push({...bad.fleet[0]});bad.fleet.push({...bad.fleet[0],slot:undefined});
const cleaned=V.sanitizeState(bad);assert.equal(cleaned.fleet.length,2);assert.ok(cleaned.fleet.every(f=>Number.isInteger(f.slot)));
let four=V.createState();four.unlockedWorlds=V.WORLDS.map(w=>w.id);four=V.startExpedition(four,'galaxies-chart',{vehicleId:'walk',role:'guide'},1).state;
for(let slot=0;slot<3;slot++)four=V.startFleet(four,slot,'galaxies-fleet',['guide','engineer','researcher'][slot],slot+1).state;
assert.equal(four.fleet.length,3);assert.ok(four.expedition);
const duplicate=V.clone(s);duplicate.expedition=V.clone(duplicate.fleet[0]);duplicate.nextId=1;
const unique=V.sanitizeState(duplicate);assert.ok(unique.fleet.every(f=>f.id!==unique.expedition.id));
const allocated=V.startFleet(unique,0,'galaxies-chart','guide',7).state;
assert.equal(new Set([allocated.expedition,...allocated.fleet].map(e=>e.id)).size,allocated.fleet.length+1);
console.log('PASS fleet: role and slot isolation, independent progress, affordable camp');
